"""Create a training notebook for a model: notebooks/<name>.ipynb.

Every notebook has the same structure (config, device, model, data, train, evaluate, predict) and
calls the shared code in imgcls/, so improvements there reach all models at once.

Examples:
    python scripts/create_notebook.py --list                      # show the presets
    python scripts/create_notebook.py --presets                   # create all preset notebooks
    python scripts/create_notebook.py resnet50                    # one preset
    python scripts/create_notebook.py swin_tiny --arch swin_tiny_patch4_window7_224.ms_in1k --lr 1e-4
    python scripts/create_notebook.py resnet50 --set EPOCHS=20 --set TRAIN_MODE=linear_probe --force

Any timm model works for --arch (python -c "import timm; print(timm.list_models('*convnext*', pretrained=True))").
Existing notebooks are never overwritten unless --force is given.
"""

import argparse
import ast
import re
import sys
from datetime import date
from pathlib import Path

import nbformat
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOK_DIR = ROOT / "notebooks"

# name -> timm architecture and settings that suit it
PRESETS = {
    "mobilenetv3_large": {"arch": "mobilenetv3_large_100.ra_in1k", "lr": 1e-3,
                          "note": "smallest and fastest; a good first run on CPU"},
    "efficientnet_b0": {"arch": "efficientnet_b0.ra_in1k", "lr": 1e-3,
                        "note": "light CNN, strong accuracy for its size"},
    "resnet50": {"arch": "resnet50.a1_in1k", "lr": 5e-4,
                 "note": "classic CNN baseline"},
    "convnext_tiny": {"arch": "convnext_tiny.fb_in22k_ft_in1k", "lr": 2e-4,
                      "note": "modern CNN pretrained on ImageNet-22k; usually the most accurate here"},
    "vit_small": {"arch": "vit_small_patch16_224.augreg_in21k_ft_in1k", "lr": 1e-4,
                  "note": "vision transformer; IMG_SIZE must stay 224"},
}


def config_fields(name, arch, lr, img_size, epochs, batch_size):
    return [
        ("MODEL_NAME", name, "results go to output/<MODEL_NAME>/<timestamp>/"),
        ("ARCH", arch, "any timm model name, e.g. timm.list_models('*convnext*', pretrained=True)"),
        ("PRETRAINED", True, "start from ImageNet weights"),
        ("DEVICE", "auto", '"auto" = GPU if available, otherwise CPU; or force "cuda" / "cpu"'),
        ("IMG_SIZE", img_size, "input resolution in pixels"),
        ("EPOCHS", epochs, ""),
        ("BATCH_SIZE", batch_size, "lower this if the GPU runs out of memory"),
        ("LR", lr, "peak learning rate (AdamW, cosine schedule, 1 warm-up epoch)"),
        ("WEIGHT_DECAY", 0.05, ""),
        ("LABEL_SMOOTHING", 0.1, ""),
        ("TRAIN_MODE", "finetune", '"finetune" = all layers; "linear_probe" = classifier only (much faster on CPU)'),
        ("VAL_FRACTION", 0.10, "share of train held out to pick the best epoch; test is only used at the end"),
        ("SAMPLES_PER_CLASS", 600, "class-balanced samples per epoch (butterfly has ~10x more images); None = every image once"),
        ("PATIENCE", None, "stop after this many epochs without val improvement; None = run all epochs"),
        ("LIMIT_PER_CLASS", None, "e.g. 20 for a quick smoke test"),
        ("NUM_WORKERS", 4, "image-loading processes"),
        ("SEED", 42, ""),
    ]


def fmt(value):
    if isinstance(value, float) and 0 < abs(value) < 0.01:
        return f"{value:.0e}".replace("e-0", "e-")
    return repr(value)


def render_config(fields):
    lines = ["# ---- settings for this model (edit freely) ----"]
    for key, value, comment in fields:
        code = f"{key} = {fmt(value)}"
        lines.append(f"{code:<30s}  # {comment}" if comment else code)
    return "\n".join(lines)


def build_notebook(name, arch, fields, note=""):
    cfg_text = render_config(fields)
    cells = [
        new_markdown_cell(
            f"# {name}\n\n"
            f"**Architecture:** `{arch}` (timm){' - ' + note if note else ''}  \n"
            f"Generated by `scripts/create_notebook.py` on {date.today().isoformat()}.\n\n"
            "Fine-tunes a pretrained model on `data/<class>/train`, keeps the epoch with the best accuracy on a "
            "validation split carved out of train, then evaluates that checkpoint once on `data/<class>/test`.\n\n"
            f"Every run is saved to `output/{name}/<timestamp>/`: `config.json`, `history.csv`, `best.pth`, "
            "`training_curves.png`, `test_metrics.json`, `confusion_matrix.png`, `misclassified.png`, "
            "`top_confusions.csv`, and `predictions.csv` for the hidden test set.\n\n"
            f"To reset this notebook: `python scripts/create_notebook.py {name} --arch {arch} --force`"),
        new_code_cell(cfg_text),
        new_markdown_cell("## Setup\nUses the GPU when one is available, otherwise the CPU (see `DEVICE`)."),
        new_code_cell(
            "import sys\n"
            "from pathlib import Path\n\n"
            "# make the shared imgcls package importable from notebooks/\n"
            "ROOT = next(p for p in [Path.cwd(), *Path.cwd().parents] if (p / \"imgcls\").is_dir())\n"
            "if str(ROOT) not in sys.path:\n"
            "    sys.path.insert(0, str(ROOT))\n\n"
            "from IPython.display import Image, display\n"
            "import imgcls\n\n"
            "imgcls.set_seed(SEED)\n"
            "device = imgcls.get_device(DEVICE)"),
        new_markdown_cell("## Model\nDownloads the pretrained weights on first use and replaces the classifier "
                          "with one output per class."),
        new_code_cell(
            "classes = imgcls.discover_classes()\n"
            "model, data_cfg = imgcls.create_model(ARCH, num_classes=len(classes), pretrained=PRETRAINED,\n"
            "                                      train_mode=TRAIN_MODE)"),
        new_markdown_cell("## Data\nTrain / validation / test counts per class. Training images get random crops, "
                          "flips, rotations and colour/lighting changes."),
        new_code_cell(
            "cfg = imgcls.config_from_globals(globals())\n"
            "data = imgcls.build_data(cfg, classes, data_cfg)"),
        new_markdown_cell("## Train\nPrints one line per epoch and saves `best.pth` whenever validation accuracy "
                          "improves. Interrupting the cell stops training early but keeps the best checkpoint."),
        new_code_cell(
            "run_dir = imgcls.train(cfg, model, data, device)\n"
            "display(Image(filename=str(run_dir / \"training_curves.png\")))"),
        new_markdown_cell("## Evaluate on the test split\nLoads `best.pth` and scores it once on the test images. "
                          "`top_confusions.csv` and `misclassified.png` are the material for the report's "
                          "failure cases."),
        new_code_cell(
            "# to evaluate an earlier run instead: run_dir = imgcls.OUTPUT_DIR / MODEL_NAME / \"<timestamp>\"\n"
            "metrics = imgcls.evaluate_run(run_dir, data, device)\n"
            "display(Image(filename=str(run_dir / \"confusion_matrix.png\")))\n"
            "if (run_dir / \"misclassified.png\").exists():\n"
            "    display(Image(filename=str(run_dir / \"misclassified.png\")))"),
        new_markdown_cell("## Predict the hidden test set\nWrites `predictions.csv` (filename, predicted category) "
                          "into the run folder."),
        new_code_cell(
            "HIDDEN_TEST_DIR = None  # e.g. r\"D:\\hidden_test_images\"\n"
            "if HIDDEN_TEST_DIR:\n"
            "    imgcls.predict_folder(run_dir / \"best.pth\", HIDDEN_TEST_DIR,\n"
            "                          out_csv=run_dir / \"predictions.csv\", device=device)"),
    ]
    nb = new_notebook(cells=cells)
    nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3 (ipykernel)", "language": "python"}
    nb.metadata["language_info"] = {"name": "python"}
    return nb


def check_arch(arch):
    import timm
    if timm.is_model(arch) or arch in timm.list_pretrained():
        return
    base = arch.split(".")[0]
    hints = timm.list_models(f"*{base}*", pretrained=True)[:10]
    sys.exit(f"Unknown timm model '{arch}'." + (f" Similar: {', '.join(hints)}" if hints else ""))


def parse_set(items):
    out = {}
    for item in items or []:
        key, _, raw = item.partition("=")
        key = key.strip().upper()
        try:
            out[key] = ast.literal_eval(raw.strip())
        except (ValueError, SyntaxError):
            out[key] = raw.strip()
    return out


def create(name, arch=None, lr=None, img_size=224, epochs=10, batch_size=32, overrides=None, force=False):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_\-]*", name):
        sys.exit(f"Model name '{name}' should use letters, digits, '_' or '-' only.")
    preset = PRESETS.get(name, {})
    arch = arch or preset.get("arch")
    if not arch:
        sys.exit(f"'{name}' is not a preset; pass --arch with a timm model name.")
    check_arch(arch)
    lr = lr if lr is not None else preset.get("lr", 3e-4)

    fields = config_fields(name, arch, lr, img_size, epochs, batch_size)
    overrides = overrides or {}
    known = {k for k, _, _ in fields}
    unknown = set(overrides) - known
    if unknown:
        sys.exit(f"--set: unknown setting(s) {sorted(unknown)}; known: {sorted(known)}")
    fields = [(k, overrides.get(k, v), c) for k, v, c in fields]

    NOTEBOOK_DIR.mkdir(exist_ok=True)
    path = NOTEBOOK_DIR / f"{name}.ipynb"
    if path.exists() and not force:
        print(f"skipped {path.relative_to(ROOT)} (exists; use --force to overwrite)")
        return path
    nbformat.write(build_notebook(name, arch, fields, preset.get("note", "")), path)
    print(f"wrote {path.relative_to(ROOT)}  [{arch}]")
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", nargs="?", help="notebook / output folder name, e.g. resnet50")
    ap.add_argument("--arch", help="timm model name (defaults to the preset's)")
    ap.add_argument("--lr", type=float)
    ap.add_argument("--img-size", type=int, default=224)
    ap.add_argument("--epochs", type=int, default=10)
    ap.add_argument("--batch-size", type=int, default=32)
    ap.add_argument("--set", action="append", metavar="KEY=VALUE", help="override any setting, e.g. --set PATIENCE=3")
    ap.add_argument("--force", action="store_true", help="overwrite an existing notebook")
    ap.add_argument("--presets", action="store_true", help="create a notebook for every preset")
    ap.add_argument("--list", action="store_true", help="list the presets")
    args = ap.parse_args()

    if args.list:
        for n, p in PRESETS.items():
            print(f"{n:20s} {p['arch']:45s} lr={fmt(p['lr']):6s} {p['note']}")
        return
    overrides = parse_set(args.set)
    if args.presets:
        for n in PRESETS:
            create(n, None, None, args.img_size, args.epochs, args.batch_size, overrides, args.force)
        return
    if not args.name:
        ap.error("give a model name, or use --presets / --list")
    create(args.name, args.arch, args.lr, args.img_size, args.epochs, args.batch_size, overrides, args.force)


if __name__ == "__main__":
    main()
